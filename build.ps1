# Boresight - Gradle-free Android build.
#
# aapt2 compiles resources and links them with the manifest into a resource-only APK,
# javac builds the sources against android.jar, d8 turns the classes into a dex, the dex
# is injected into the APK, then zipalign and uber-apk-signer finish it.
#
#   .\build.ps1              build, sign
#   .\build.ps1 -Install     also install over adb
#   .\build.ps1 -Run         also install and launch

param(
    [switch]$Install,
    [switch]$Run,
    [switch]$Clean
)

# Native tools write notes and warnings to stderr, which PowerShell promotes to an
# error record. Exit codes are checked explicitly instead.
$ErrorActionPreference = "Continue"

$root      = $PSScriptRoot
$sdk       = "C:\tools\android-sdk"
$buildTool = "$sdk\build-tools\35.0.0"
$platform  = "$sdk\platforms\android-35\android.jar"
$adb       = "C:\tools\android_platform-tools\adb.exe"
$signer    = "C:\tools\apktool\uber-apk-signer.jar"

$pkg   = "com.boresight"
# Third-party jars (the Shizuku API and its aidl/shared companions), unpacked from
# their AARs into libs/. Compiled against and dexed in; nothing else is pulled.
$libsJars = @()
if (Test-Path "$root\libs") {
    $libsJars = @(Get-ChildItem "$root\libs" -Filter *.jar | ForEach-Object { $_.FullName })
}
$cpSep = [IO.Path]::PathSeparator
$fullCp = (@($platform) + $libsJars) -join $cpSep
$build = "$root\build"

if ($Clean -and (Test-Path $build)) { Remove-Item -Recurse -Force $build }
New-Item -ItemType Directory -Force "$build\res", "$build\classes", "$build\signed" | Out-Null

function Fail($msg) { Write-Host "FAILED: $msg" -ForegroundColor Red; exit 1 }

# --- 1. compile resources -------------------------------------------------
Write-Host "[1/6] aapt2 compile" -ForegroundColor Cyan
Get-ChildItem "$build\res" -Filter *.flat -ErrorAction SilentlyContinue | Remove-Item -Force
& "$buildTool\aapt2.exe" compile --dir "$root\res" -o "$build\res" 2>&1 | ForEach-Object { $_ }
if ($LASTEXITCODE -ne 0) { Fail "aapt2 compile" }

# aapt2 compile --dir emits one zip; unpack so link gets the flat files.
$zip = Get-ChildItem "$build\res" -Filter *.zip -ErrorAction SilentlyContinue | Select-Object -First 1
if ($zip) {
    Expand-Archive -Path $zip.FullName -DestinationPath "$build\res" -Force
    Remove-Item $zip.FullName -Force
}

# --- 2. link into a resource APK -----------------------------------------
Write-Host "[2/6] aapt2 link" -ForegroundColor Cyan
$flats = Get-ChildItem "$build\res" -Filter *.flat | ForEach-Object { $_.FullName }
if ($flats.Count -eq 0) { Fail "no compiled resources" }

$linkArgs = @(
    "link",
    "-I", $platform,
    "--manifest", "$root\AndroidManifest.xml",
    "--java", "$build\gen",
    "--min-sdk-version", "29",
    "--target-sdk-version", "35",
    "--auto-add-overlay",
    "-o", "$build\base.apk"
)
if (Test-Path "$root\assets") { $linkArgs += @("-A", "$root\assets") }
New-Item -ItemType Directory -Force "$build\gen" | Out-Null
& "$buildTool\aapt2.exe" @linkArgs $flats 2>&1 | ForEach-Object { $_ }
if ($LASTEXITCODE -ne 0) { Fail "aapt2 link" }

# --- 2b. build stamp ------------------------------------------------------
# Generated rather than committed: it has to change on every build, and a tracked
# file that changes on every build makes every diff noisy and every commit a lie.
# build\gen is already on javac's source list, so it compiles in for free.
#
# This exists so a bug report can name an exact build. "Version 2.0" was the answer
# for every release ever cut, which is the same as having no answer.
$verName = ([regex]::Match(
    [System.IO.File]::ReadAllText("$root\AndroidManifest.xml", [System.Text.Encoding]::UTF8),
    'android:versionName="([^"]*)"')).Groups[1].Value
$commit = (& C:\tools\git\cmd\git.exe -C $root rev-parse --short HEAD 2>$null)
if (-not $commit) { $commit = "unknown" }
$dirty = (& C:\tools\git\cmd\git.exe -C $root status --porcelain 2>$null)
if ($dirty) { $commit = "$commit+" }   # '+' means there were uncommitted changes
$built = (Get-Date).ToUniversalTime().ToString("yyyy-MM-dd HH:mm 'UTC'")

New-Item -ItemType Directory -Force "$build\gen\com\boresight" | Out-Null
$stamp = @"
package com.boresight;

/** Generated by build.ps1. Identifies exactly which build this is. */
public final class Stamp {
    private Stamp() { }
    public static final String VERSION = "$verName";
    /** Short commit, with a trailing '+' if the tree had uncommitted changes. */
    public static final String COMMIT  = "$commit";
    public static final String BUILT   = "$built";
}
"@
[System.IO.File]::WriteAllText("$build\gen\com\boresight\Stamp.java", $stamp,
    (New-Object System.Text.UTF8Encoding $false))

# --- 3. javac -------------------------------------------------------------
Write-Host "[3/6] javac" -ForegroundColor Cyan
$src = Get-ChildItem -Recurse "$root\src" -Filter *.java | ForEach-Object { $_.FullName }
$gen = Get-ChildItem -Recurse "$build\gen" -Filter *.java -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName }
$all = @($src) + @($gen)
# -encoding matters: javac otherwise reads sources as the Windows ANSI codepage and
# every non-ASCII character in a string literal arrives on screen as mojibake.
$jout = & javac --release 11 -encoding UTF-8 -nowarn -Xlint:none `
    -classpath $fullCp -d "$build\classes" @all 2>&1
if ($LASTEXITCODE -ne 0) {
    $jout | Where-Object { $_ -match "error" } | Select-Object -First 25 | ForEach-Object { Write-Host $_ }
    Fail "javac"
}

# --- 4. d8 ----------------------------------------------------------------
Write-Host "[4/6] d8" -ForegroundColor Cyan
# Several hundred class files (every anonymous inner class is its own) blow past the
# Windows command line limit, so they go to d8 as a single jar.
Remove-Item "$build\classes.jar" -Force -ErrorAction SilentlyContinue
& jar --create --file "$build\classes.jar" -C "$build\classes" . 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) { Fail "jar" }

$dout = & "$buildTool\d8.bat" --release --min-api 29 --lib $platform `
    --output "$build" "$build\classes.jar" @libsJars 2>&1
if ($LASTEXITCODE -ne 0) {
    $dout | Select-Object -First 25 | ForEach-Object { Write-Host $_ }
    Fail "d8"
}

# --- 5. package -----------------------------------------------------------
Write-Host "[5/6] package" -ForegroundColor Cyan
Copy-Item "$build\base.apk" "$build\unsigned.apk" -Force

# The dex has to sit at the archive root, so stage it in its own directory and add it there.
$stage = "$build\stage"
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force $stage | Out-Null
Copy-Item "$build\classes.dex" "$stage\classes.dex" -Force
if (Test-Path "$build\classes2.dex") { Copy-Item "$build\classes2.dex" "$stage\classes2.dex" -Force }

Push-Location $stage
try {
    $dexes = Get-ChildItem -Filter *.dex | ForEach-Object { $_.Name }
    & "$sdk\build-tools\35.0.0\aapt.exe" add -f "$build\unsigned.apk" @dexes 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) {
        # Newer build-tools drop aapt; fall back to .NET zip.
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        $z = [System.IO.Compression.ZipFile]::Open("$build\unsigned.apk", "Update")
        foreach ($d in $dexes) {
            $old = $z.GetEntry($d)
            if ($old) { $old.Delete() }
            [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
                $z, (Join-Path $stage $d), $d) | Out-Null
        }
        $z.Dispose()
    }
} finally { Pop-Location }

Remove-Item "$build\aligned.apk" -Force -ErrorAction SilentlyContinue
& "$buildTool\zipalign.exe" -p -f 4 "$build\unsigned.apk" "$build\aligned.apk" 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) { Fail "zipalign" }

# --- 6. sign --------------------------------------------------------------
Write-Host "[6/6] sign" -ForegroundColor Cyan
Get-ChildItem "$build\signed" -ErrorAction SilentlyContinue | Remove-Item -Force -Recurse
# --overwrite is mutually exclusive with --out; the debug keystore is generated for us.
& java -jar $signer --apks "$build\aligned.apk" --out "$build\signed" --allowResign 2>&1 |
    Select-String -Pattern "signed|verified|error|Exception" | ForEach-Object { $_ }

$apk = Get-ChildItem "$build\signed" -Filter *.apk | Select-Object -First 1
if (-not $apk) { Fail "signing produced no apk" }

$kb = [math]::Round($apk.Length / 1024, 1)
Write-Host ""
Write-Host "built $($apk.Name)  ${kb} KB" -ForegroundColor Green

if ($Install -or $Run) {
    Write-Host "installing" -ForegroundColor Cyan
    & $adb install -r -d $apk.FullName 2>&1 | Select-Object -Last 3
    if ($Run) {
        & $adb shell am start -n "$pkg/$pkg.MainActivity" 2>&1 | Select-Object -Last 2
    }
}
